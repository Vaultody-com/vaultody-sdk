"""Loads the shared test vectors (../../../test-vectors/v1.json) and turns cases into verifier inputs.

The vectors are generated by the API gateway with test-only keys and are the single source of truth
for the wire format; every helper language must reach exactly their verdicts.
"""

import base64
import json
from pathlib import Path

from cryptography.hazmat.primitives import serialization

VECTORS_DIR = Path(__file__).resolve().parents[3] / "test-vectors"
VECTORS_PATH = VECTORS_DIR / "v1.json"
VECTORS = json.loads(VECTORS_PATH.read_text(encoding="utf-8"))
CASES = VECTORS["cases"]
SKEW_SECONDS = VECTORS["verifier"]["skewSeconds"]


def load(name):
    """Another shared vector set, by file name."""
    return json.loads((VECTORS_DIR / name).read_text(encoding="utf-8"))


def case(name):
    return next(candidate for candidate in CASES if candidate["name"] == name)


def root_der(name):
    return base64.b64decode(VECTORS["keys"]["roots"][name]["publicKeySpkiDerBase64"])


def root_pem(name):
    key = serialization.load_der_public_key(root_der(name))
    return key.public_bytes(serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo).decode("ascii")


def root_id(name):
    return VECTORS["keys"]["roots"][name]["rootId"]


def url_of(sent):
    """The path and query as they went on the wire."""
    assert "?" not in sent["path"], "a vector path must not hold a query"
    return sent["path"] + ("?" + sent["query"] if sent["query"] else "")


def inputs(vector):
    """(request, response, keyword arguments) for verify_response, from one vector."""
    verify = vector["verify"]
    sent = verify["request"]
    received = verify["response"]
    request = {
        "method": sent["method"],
        "url": url_of(sent),
        "body": base64.b64decode(sent["bodyBase64"]),
        "api_sign": sent["apiSign"],
        "keypair_sign": sent["keypairSign"],
    }
    response = {
        "status": received["status"],
        "headers": dict(received["headers"]),
        "body": base64.b64decode(received["bodyBase64"]),
    }
    options = {
        "roots": [root_der(name) for name in verify["pinnedRoots"]],
        "now": verify["now"],
        "max_clock_skew_seconds": SKEW_SECONDS,
    }
    return request, response, options
