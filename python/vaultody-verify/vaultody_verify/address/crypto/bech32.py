"""Bech32 encoding of version 0 segwit addresses (BIP 173).

A trimmed port of the BIP 173 reference implementation, ``ref/python/segwit_addr.py`` in
github.com/sipa/bech32 (MIT licence, commit ef0181a25c644e0404180d977da19f7c5d441f89). Only encoding is kept,
and only Bech32 proper: every address the Vaultody server makes is witness version 0, which BIP 350 left on
Bech32 (Bech32m is for version 1 and up). ``convertbits`` is shared with the CashAddr encoder.
"""

CHARSET = "qpzry9x8gf2tvdw0s3jn54khce6mua7l"


def bech32_polymod(values):
    """Internal function that computes the Bech32 checksum."""
    generator = [0x3b6a57b2, 0x26508e6d, 0x1ea119fa, 0x3d4233dd, 0x2a1462b3]
    chk = 1
    for value in values:
        top = chk >> 25
        chk = (chk & 0x1ffffff) << 5 ^ value
        for i in range(5):
            chk ^= generator[i] if ((top >> i) & 1) else 0
    return chk


def bech32_hrp_expand(hrp):
    """Expand the HRP into values for checksum computation."""
    return [ord(x) >> 5 for x in hrp] + [0] + [ord(x) & 31 for x in hrp]


def bech32_create_checksum(hrp, data):
    """Compute the checksum values given HRP and data."""
    values = bech32_hrp_expand(hrp) + data
    polymod = bech32_polymod(values + [0, 0, 0, 0, 0, 0]) ^ 1
    return [(polymod >> 5 * (5 - i)) & 31 for i in range(6)]


def bech32_encode(hrp, data):
    """Compute a Bech32 string given HRP and data values."""
    combined = data + bech32_create_checksum(hrp, data)
    return hrp + '1' + ''.join([CHARSET[d] for d in combined])


def convertbits(data, frombits, tobits, pad=True):
    """General power-of-2 base conversion."""
    acc = 0
    bits = 0
    ret = []
    maxv = (1 << tobits) - 1
    max_acc = (1 << (frombits + tobits - 1)) - 1
    for value in data:
        if value < 0 or (value >> frombits):
            return None
        acc = ((acc << frombits) | value) & max_acc
        bits += frombits
        while bits >= tobits:
            bits -= tobits
            ret.append((acc >> bits) & maxv)
    if pad:
        if bits:
            ret.append((acc << (tobits - bits)) & maxv)
    elif bits >= frombits or ((acc << (tobits - bits)) & maxv):
        return None
    return ret


def encode_segwit_v0(hrp, witprog):
    """Encode a version 0 segwit address (a 20-byte P2WPKH or 32-byte P2WSH program)."""
    witprog = bytes(witprog)
    if len(witprog) not in (20, 32):
        raise ValueError("a version 0 witness program is 20 or 32 bytes")
    return bech32_encode(hrp, [0] + convertbits(witprog, 8, 5))
